#!/bin/sh
# Schreibt admob-runtime.mjs ins App-Bundle: Debug = Test-Anzeigen, Release = echte IDs.
# Muss nach "Copy Bundle Resources" laufen (npm run sync legt die Datei unter public/game/app/ ab).
set -e
FLAG=true
if [ "$CONFIGURATION" = "Release" ]; then
  FLAG=false
fi
DIR=""
for d in \
  "${TARGET_BUILD_DIR}/${UNLOCALIZED_RESOURCES_FOLDER_PATH}/public/game/app" \
  "${BUILT_PRODUCTS_DIR}/${PRODUCT_NAME}.app/public/game/app"
do
  if [ -d "$d" ]; then
    DIR="$d"
    break
  fi
done
if [ -z "$DIR" ]; then
  echo "warning: public/game/app nicht im Bundle (zuerst npm run sync im Ordner app/)"
  if [ "$CONFIGURATION" = "Release" ]; then
    echo "error: Release-Build ohne Web-Bundle, AdMob-Runtime kann nicht gesetzt werden"
    exit 1
  fi
  exit 0
fi
printf '// generated by Xcode (%s)\nexport const ADMOB_TESTING = %s;\n' "$CONFIGURATION" "$FLAG" > "$DIR/admob-runtime.mjs"
echo "AdMob-Runtime: ADMOB_TESTING=$FLAG ($CONFIGURATION) -> $DIR/admob-runtime.mjs"
